import {
  AddressType,
  CodeDisplay,
  ContactPointInfo,
  DiseaseStatus,
  FacilityAddressInfo,
  FacilityInfo,
  NotifiedPersonAddressInfo,
  NotifiedPersonBasicInfo,
  PractitionerInfo,
} from '../../api/notification';
import { ExtendedSalutationType } from '../legacy/common-utils';

/** An answer node of a required field, as generated for keys like `<linkId>.answer.<valueKey>`; always filled once the form is valid. */
export type RequiredAnswerNode<ValueKey extends string, Value> = { answer: Record<ValueKey, Value> };

/** The answer node of an optional field, which may be missing or empty. */
export type AnswerNode<ValueKey extends string, Value> = { answer?: Partial<RequiredAnswerNode<ValueKey, Value>['answer']> };

/** Email addresses and phone numbers, entered in two separate lists. */
export interface ContactLists {
  emailAddresses: ContactPointInfo[];
  phoneNumbers: ContactPointInfo[];
}

/** Model of the notifier step. */
export interface NotifierStepModel {
  address: FacilityAddressInfo;
  contact: Omit<PractitionerInfo, 'salutation'> & { salutation?: ExtendedSalutationType };
  contacts: ContactLists;
  facilityInfo: Omit<FacilityInfo, 'organizationType'> & { organizationType: RequiredAnswerNode<'valueCoding', CodeDisplay> };
  /** Honeypot; must be sent unchanged so that the gateway can detect bots. */
  oneTimeCode?: string;
}

/** Model of the notified person step; which parts are used depends on the notification type. */
export interface NotifiedPersonStepModel {
  info: NotifiedPersonBasicInfo;
  residenceAddress: NotifiedPersonAddressInfo;
  residenceAddressType?: AddressType;
  currentAddress?: NotifiedPersonAddressInfo;
  currentAddressType?: AddressType;
  currentAddressInstitutionName?: string;
  contacts: ContactLists;
}

/** Model of the notification category step: the chosen disease and its status. */
export interface NotificationCategoryStepModel {
  diseaseChoice: RequiredAnswerNode<'valueCoding', CodeDisplay>;
  clinicalStatus: RequiredAnswerNode<'valueString', DiseaseStatus.StatusEnum>;
  statusNoteGroup: {
    statusNote?: AnswerNode<'valueString', string>;
    notificationIdReference: RequiredAnswerNode<'valueString', DiseaseStatus.NotificationIdReferenceEnum>;
    initialNotificationId?: AnswerNode<'valueString', string>;
  };
}

/** Model of the condition step; evidence is a multi-select or, in older models, a list of single answers. */
export interface ConditionStepModel {
  recordedDate?: AnswerNode<'valueDate', string>;
  onset?: AnswerNode<'valueDate', string>;
  note?: AnswerNode<'valueString', string>;
  evidence?: AnswerNode<'valueCoding', CodeDisplay[]> | RequiredAnswerNode<'valueCoding', CodeDisplay>[];
}

/**
 * Model of a valid disease notification form, one entry per navigation step.
 * The questionnaire steps follow the questionnaire-specific field keys generated by FUTS.
 */
export interface DiseaseFormModel {
  notifier: NotifierStepModel;
  notifiedPerson: NotifiedPersonStepModel;
  notificationCategory: NotificationCategoryStepModel;
  condition: ConditionStepModel;
  commonQuestionnaire: Record<string, unknown>;
  specificQuestionnaire: Record<string, unknown>;
}

/** Key of a step in the side-navigation disease notification form. */
export type DiseaseStepKey = keyof DiseaseFormModel;

/** All form steps, in the order in which they are presented in the side navigation. */
export const DISEASE_STEP_KEYS: readonly DiseaseStepKey[] = [
  'notifier',
  'notifiedPerson',
  'notificationCategory',
  'condition',
  'commonQuestionnaire',
  'specificQuestionnaire',
];
