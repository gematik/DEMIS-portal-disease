import { FormlyFieldConfig } from '@ngx-formly/core';
import { describe, expect, it } from 'vitest';
import { MOCK_KLINISCHE_ANGABE_QUESTIONS } from '../../test/shared/data/mocked_common_disease';
import { EXAMPLE_MSVD } from '../../test/shared/data/test-values';
import { EXAMPLE_TOXP_SHORT } from '../../test/shared/data/test-values-nonnominal';
import { EXAMPLE_MSVD_SHORT } from '../../test/shared/data/test-values-short';
import { formatItems, makeFieldSequence, sortItems } from '../format-items';
import { findQuantityFieldsByProp } from '../shared/utils';
import { toQuestionnaireResponseItems } from './questionnaire-response.mapper';

const coding = (code: string) => ({ code, system: 'https://example.org', display: code, designations: [{ language: 'de', value: code }] });

/** Field layout as generated by FUTS: `<linkId>.answer` groups, value keys and repeat sections. */
const HOSPITALIZATION_FIELDS: FormlyFieldConfig[] = [
  {
    key: 'hospitalized.answer',
    fieldGroup: [
      { key: 'valueCoding', type: 'radio-button-coding' },
      {
        key: 'repeat-section-1',
        type: 'repeat-section',
        fieldArray: {
          fieldGroup: [
            {
              key: 'hospitalizedGroup',
              fieldGroup: [
                {
                  key: 'hospitalizedEncounter.answer',
                  fieldGroup: [
                    {
                      key: 'Hospitalization',
                      fieldGroup: [
                        { key: 'serviceType', fieldGroup: [{ key: 'answer.valueCoding', type: 'autocomplete-coding' }] },
                        {
                          key: 'period',
                          fieldGroup: [
                            { key: 'start', fieldGroup: [{ key: 'answer.valueDate', type: 'datepicker' }] },
                            { key: 'end', fieldGroup: [{ key: 'answer.valueDate', type: 'datepicker' }] },
                          ],
                        },
                      ],
                    },
                  ],
                },
              ],
            },
          ],
        },
      },
    ],
  },
  { key: 'note', fieldGroup: [{ key: 'answer.valueString', type: 'textarea' }] },
];

const hospitalizedGroup = (start: string) => ({
  hospitalizedGroup: {
    hospitalizedEncounter: {
      answer: {
        Hospitalization: {
          period: { end: { answer: { valueDate: '2024-02-01' } }, start: { answer: { valueDate: start } } },
          serviceType: { answer: { valueCoding: { code: 'INN' } } },
        },
      },
    },
  },
});

const hospitalizationItem = (start: string) => ({
  linkId: 'hospitalizedGroup',
  item: [
    {
      linkId: 'hospitalizedEncounter',
      answer: [
        {
          item: [
            {
              linkId: 'Hospitalization',
              item: [
                { linkId: 'serviceType', answer: [{ valueCoding: { code: 'INN' } }] },
                {
                  linkId: 'period',
                  item: [
                    { linkId: 'start', answer: [{ valueDate: start }] },
                    { linkId: 'end', answer: [{ valueDate: '2024-02-01' }] },
                  ],
                },
              ],
            },
          ],
        },
      ],
    },
  ],
});

describe('toQuestionnaireResponseItems', () => {
  it('builds nested items in field order, regardless of the model order', () => {
    const model = {
      note: { answer: { valueString: 'remark' } },
      hospitalized: { answer: { 'repeat-section-1': [hospitalizedGroup('2024-01-01')], valueCoding: { code: 'yes' } } },
    };

    expect(toQuestionnaireResponseItems(model, HOSPITALIZATION_FIELDS)).toEqual([
      {
        linkId: 'hospitalized',
        answer: [{ valueCoding: { code: 'yes' }, item: [{ linkId: 'repeat-section-1', item: [hospitalizationItem('2024-01-01')] }] }],
      },
      { linkId: 'note', answer: [{ valueString: 'remark' }] },
    ]);
  });

  it('describes repeat sections by their template even after Formly has built their entries', () => {
    const builtFields = structuredClone(HOSPITALIZATION_FIELDS);
    const repeatSection = builtFields[0].fieldGroup![1];
    repeatSection.fieldGroup = [0, 1].map(key => ({ key, fieldGroup: structuredClone((repeatSection.fieldArray as FormlyFieldConfig).fieldGroup) }));
    const model = { hospitalized: { answer: { 'repeat-section-1': [hospitalizedGroup('2024-01-01'), hospitalizedGroup('2024-01-15')] } } };

    expect(toQuestionnaireResponseItems(model, builtFields)).toEqual([
      {
        linkId: 'hospitalized',
        answer: [{ item: [{ linkId: 'repeat-section-1', item: [hospitalizationItem('2024-01-01'), hospitalizationItem('2024-01-15')] }] }],
      },
    ]);
  });

  it('answers checkboxes with booleans', () => {
    const fields: FormlyFieldConfig[] = [{ key: 'copyNotifierContact', type: 'checkbox' }];

    expect(toQuestionnaireResponseItems({ copyNotifierContact: false }, fields)).toEqual([
      { linkId: 'copyNotifierContact', answer: [{ valueBoolean: false }] },
    ]);
  });

  describe('quantities', () => {
    const fields: FormlyFieldConfig[] = [
      {
        key: 'pregnancyWeek.answer',
        fieldGroup: [{ key: 'pregnancyWeek', type: 'input', props: { quantity: { system: 'http://unitsofmeasure.org', unit: null, code: 'wk' } } }],
      },
    ];

    it('answers with the unit of the quantity field', () => {
      expect(toQuestionnaireResponseItems({ pregnancyWeek: { answer: { pregnancyWeek: 12 } } }, fields)).toEqual([
        { linkId: 'pregnancyWeek', answer: [{ valueQuantity: { value: 12, unit: null, system: 'http://unitsofmeasure.org', code: 'wk' } }] },
      ]);
    });

    it.each([null, undefined, ''])('leaves the item unanswered for an empty value %j', value => {
      expect(toQuestionnaireResponseItems({ pregnancyWeek: { answer: { pregnancyWeek: value } } }, fields)).toEqual([{ linkId: 'pregnancyWeek' }]);
    });
  });

  it('answers once per selected coding and omits designations without changing the model', () => {
    const fields: FormlyFieldConfig[] = [
      { key: 'evidence.answer', fieldGroup: [{ key: 'valueCoding', type: 'autocomplete-multi-coding' }] },
      { key: 'reason.answer', fieldGroup: [{ key: 'valueCoding', type: 'autocomplete-coding' }] },
    ];
    const model = { evidence: { answer: { valueCoding: [coding('a'), coding('b')] } }, reason: { answer: { valueCoding: coding('c') } } };
    const original = structuredClone(model);

    expect(toQuestionnaireResponseItems(model, fields)).toEqual([
      {
        linkId: 'evidence',
        answer: [
          { valueCoding: { code: 'a', system: 'https://example.org', display: 'a' } },
          { valueCoding: { code: 'b', system: 'https://example.org', display: 'b' } },
        ],
      },
      { linkId: 'reason', answer: [{ valueCoding: { code: 'c', system: 'https://example.org', display: 'c' } }] },
    ]);
    expect(model).toEqual(original);
  });

  // RETIRING(FEATURE_FLAG_CORE_SIDENAV): Remove this comparison together with the legacy format-items.
  describe('equivalence with the legacy conversion', () => {
    const asFields = (fields: unknown) => fields as FormlyFieldConfig[];

    it.each([
      ['MSVD common', asFields(EXAMPLE_MSVD.commonConfig)],
      ['MSVD specific', asFields(EXAMPLE_MSVD.questionnaireConfigs)],
      ['MSVD short common', asFields(EXAMPLE_MSVD_SHORT.commonConfig)],
      ['MSVD short specific', asFields(EXAMPLE_MSVD_SHORT.questionnaireConfigs)],
      ['TOXP specific', asFields(EXAMPLE_TOXP_SHORT.questionnaireConfigs)],
      ['clinical common', asFields(MOCK_KLINISCHE_ANGABE_QUESTIONS.fieldGroup)],
    ])('produces the legacy items for a completely filled %s questionnaire', (_, fields) => {
      // The legacy sort keeps the model order for some nested items, so it gets the model in field order.
      const legacyItems = formatItems(fillModel(fields, 'fieldOrder'), findQuantityFieldsByProp(fields));
      sortItems(legacyItems, makeFieldSequence(fields));

      const items = toQuestionnaireResponseItems(fillModel(fields, 'reversed'), fields);

      expect(items.length).toBeGreaterThan(0);
      // The legacy conversion nulls designations instead of omitting them; the gateway ignores both.
      expect(items).toEqual(JSON.parse(JSON.stringify(legacyItems, (key, value) => (key === 'designations' ? undefined : value))));
    });
  });
});

/** Fills every field of a FUTS questionnaire, inserting the model entries in field order or reversed. */
function fillModel(fields: readonly FormlyFieldConfig[], order: 'fieldOrder' | 'reversed', model: Record<string, any> = {}): Record<string, any> {
  (order === 'reversed' ? [...fields].reverse() : fields).forEach(field => {
    const path = field.key === undefined ? [] : String(field.key).split('.');
    if (field.fieldArray) {
      const template = field.fieldArray as FormlyFieldConfig;
      assign(model, path, [fillModel([template], order), fillModel([template], order)]);
    } else if (field.fieldGroup) {
      fillModel(field.fieldGroup, order, descend(model, path));
    } else if (path.length > 0) {
      assign(model, path, sampleValue(field));
    }
  });
  return model;
}

function descend(model: Record<string, any>, path: string[]): Record<string, any> {
  return path.reduce((node, key) => (node[key] ??= {}), model);
}

function assign(model: Record<string, any>, path: string[], value: unknown): void {
  descend(model, path.slice(0, -1))[path.at(-1)!] = value;
}

function sampleValue(field: FormlyFieldConfig): unknown {
  switch (field.type) {
    case 'checkbox':
      return true;
    case 'autocomplete-multi-coding':
      return [coding('first'), coding('second')];
    case 'autocomplete-coding':
    case 'radio-button-coding':
    case 'select-coding':
      return coding(String(field.key));
    case 'datepicker':
      return '2024-05-01';
    default:
      return field.props?.['quantity'] || field.props?.type === 'number' ? 7 : `text ${String(field.key)}`;
  }
}
