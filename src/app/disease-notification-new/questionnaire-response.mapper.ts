import { FormlyFieldConfig } from '@ngx-formly/core';
import { CodeDisplay, Quantity, QuestionnaireResponseAnswer, QuestionnaireResponseItem } from '../../api/notification';

/** Questionnaire structure derived from the Formly fields, one node per linkId. */
interface ItemShape {
  /** Rank of the item's first field within the questionnaire; items are sorted by it. */
  readonly position: number;
  /** Shapes of the child items, keyed by linkId; covers group children and answer children alike. */
  readonly children: Map<string, ItemShape>;
  /** Set when the item is answered with a quantity input. */
  quantity?: Omit<Quantity, 'value'>;
}

/** A key-value pair of a Formly model object, as returned by `Object.entries`. */
type ModelEntry = [key: string, value: unknown];

/** Whether a model key holds the answer of an item (`answer`) instead of a child item. */
const isAnswerKey = (key: string): boolean => key.startsWith('answer');
/** Whether a model key holds an answer value (`valueString`, `valueCoding`, ...) instead of a child item. */
const isValueKey = (key: string): boolean => key.startsWith('value');
/** Whether a value is a plain model object, i.e. neither a primitive, `null` nor an array. */
const isRecord = (value: unknown): value is Record<string, unknown> => typeof value === 'object' && value !== null && !Array.isArray(value);

/**
 * Converts the Formly model of a questionnaire step into QuestionnaireResponse items.
 *
 * The model follows the field keys generated by FUTS: each item is stored under its linkId, its answer
 * values under `answer.value*`, child items next to `answer` (group items) or inside it (answer items),
 * and repetitions as an array under `repeat-section-<n>`. Items are ordered like their fields, because
 * the questionnaire validation requires questionnaire order.
 *
 * @param model Model of one questionnaire step; it is not modified.
 * @param fields Formly fields of the same step, before or after Formly has built them.
 * @returns Items in questionnaire order.
 */
export function toQuestionnaireResponseItems(model: Record<string, unknown>, fields: FormlyFieldConfig[]): QuestionnaireResponseItem[] {
  return toItems(Object.entries(model), describeItems(fields));
}

/**
 * Derives the questionnaire structure from the Formly fields.
 *
 * Fields are visited depth-first in their configured order. Each linkId in a field key creates a node
 * the first time it occurs, and that occurrence defines the node's position. `answer` and `value*`
 * segments are skipped, so answer children end up below their item, e.g. the keys
 * `hospitalized.answer` > `repeat-section-1` > `hospitalizedGroup` result in the path
 * `hospitalized` > `repeat-section-1` > `hospitalizedGroup`.
 *
 * @param fields Formly fields of one questionnaire step.
 * @returns Root node whose children are the top-level items.
 */
function describeItems(fields: FormlyFieldConfig[]): ItemShape {
  const root: ItemShape = { position: 0, children: new Map() };
  let position = 0;

  /** Returns the child node for a linkId, creating it at the next position on first use. */
  const childShape = (parent: ItemShape, linkId: string): ItemShape => {
    let child = parent.children.get(linkId);
    if (!child) {
      child = { position: ++position, children: new Map() };
      parent.children.set(linkId, child);
    }
    return child;
  };

  /** Adds the linkIds of a field below `parent` and continues with its child fields. */
  const visit = (field: FormlyFieldConfig, parent: ItemShape): void => {
    const quantity = field.props?.['quantity'];
    if (quantity) {
      // FUTS keys a quantity input with the linkId of its enclosing `<linkId>.answer` group.
      parent.quantity = { unit: quantity.unit, system: quantity.system, code: quantity.code };
    }
    let shape = parent;
    for (const linkId of linkIdsOf(field.key)) {
      shape = childShape(shape, linkId);
    }
    templateOrChildren(field).forEach(child => visit(child, shape));
  };

  fields.forEach(field => visit(field, root));
  return root;
}

/**
 * Extracts the linkIds from a Formly field key.
 *
 * @param key Field key, e.g. `name.given.answer.valueString`.
 * @returns The linkIds in key order, e.g. `['name', 'given']`; empty for fields without key.
 */
function linkIdsOf(key: FormlyFieldConfig['key']): string[] {
  if (key === undefined || key === null) {
    return [];
  }
  return String(key)
    .split('.')
    .filter(segment => !isAnswerKey(segment) && !isValueKey(segment));
}

/**
 * Returns the fields that describe the children of a field.
 *
 * Formly copies a repeat-section template into `fieldGroup` once per entry (with keys `0`, `1`, ...),
 * so the template alone describes all entries.
 *
 * @param field Field whose children are requested.
 * @returns The repeat-section template, otherwise the field group (empty for leaf fields).
 */
function templateOrChildren(field: FormlyFieldConfig): FormlyFieldConfig[] {
  const { fieldArray, fieldGroup = [] } = field;
  if (!fieldArray) {
    return fieldGroup;
  }
  const template = typeof fieldArray === 'function' ? fieldArray(field) : fieldArray;
  return [template];
}

/**
 * Converts model entries into items, sorted by questionnaire position.
 *
 * Entries without a field keep their model order and precede known items, like in the legacy conversion.
 *
 * @param entries Model entries keyed by linkId; the array is sorted in place.
 * @param shape Node of the enclosing item, or `undefined` if the fields do not describe it.
 * @returns One item per entry.
 */
function toItems(entries: ModelEntry[], shape: ItemShape | undefined): QuestionnaireResponseItem[] {
  const positionOf = (linkId: string): number => shape?.children.get(linkId)?.position ?? 0;
  entries.sort(([a], [b]) => positionOf(a) - positionOf(b));
  return entries.map(([linkId, value]) => {
    const itemShape = shape?.children.get(linkId);
    return toItem(linkId, value, itemShape);
  });
}

/**
 * Converts the model value of one linkId into an item.
 *
 * - `boolean` (checkbox): an answer with `valueBoolean`.
 * - Quantity input: an answer with `valueQuantity` and the unit from the field; no answer while empty.
 * - Array (`repeat-section-<n>`): one item containing the children of all repetitions; the gateway
 *   replaces it with these children.
 * - Object: answers from `answer` and child items from all other keys.
 * - Anything else, e.g. `null`: an item without answer, which the gateway discards.
 *
 * @param linkId linkId of the item.
 * @param value Model value stored under the linkId.
 * @param shape Node of the item, or `undefined` if the fields do not describe it.
 * @returns The item.
 */
function toItem(linkId: string, value: unknown, shape: ItemShape | undefined): QuestionnaireResponseItem {
  if (typeof value === 'boolean') {
    return { linkId, answer: [{ valueBoolean: value }] };
  }
  if (shape?.quantity) {
    return toQuantityItem(linkId, value, shape.quantity);
  }
  if (Array.isArray(value)) {
    return toRepeatSectionItem(linkId, value, shape);
  }
  if (isRecord(value)) {
    return toItemFromObject(linkId, value, shape);
  }
  return { linkId };
}

/**
 * Converts the model value of a quantity input into an item.
 *
 * FUTS keys the input with the linkId of its item, so the amount is stored under `answer.<linkId>`.
 *
 * @param linkId linkId of the item.
 * @param value Model value stored under the linkId.
 * @param quantity Unit of the quantity field.
 * @returns The item with a `valueQuantity` answer, or without answer while the input is empty.
 */
function toQuantityItem(linkId: string, value: unknown, quantity: Omit<Quantity, 'value'>): QuestionnaireResponseItem {
  const answer = isRecord(value) ? value['answer'] : undefined;
  const amount = isRecord(answer) ? answer[linkId] : undefined;
  if (amount === undefined || amount === null || amount === '') {
    return { linkId };
  }
  const valueQuantity: Quantity = { value: amount as number, ...quantity };
  return { linkId, answer: [{ valueQuantity }] };
}

/**
 * Converts the repetitions of a repeat section into one item holding the children of all repetitions.
 *
 * @param linkId Key of the repeat section, e.g. `repeat-section-1`; the gateway replaces the item with its children.
 * @param repetitions Model objects of the repetitions.
 * @param shape Node of the repeat section; its children describe the items of one repetition.
 * @returns The repeat-section item.
 */
function toRepeatSectionItem(linkId: string, repetitions: unknown[], shape: ItemShape | undefined): QuestionnaireResponseItem {
  const entries = repetitions.flatMap(childEntries);
  const children = toItems(entries, shape);
  return withChildren({ linkId }, children);
}

/**
 * Converts the model object of an item into an item with its answers and child items.
 *
 * @param linkId linkId of the item.
 * @param value Model object stored under the linkId.
 * @param shape Node of the item, or `undefined` if the fields do not describe it.
 * @returns The item.
 */
function toItemFromObject(linkId: string, value: Record<string, unknown>, shape: ItemShape | undefined): QuestionnaireResponseItem {
  const item: QuestionnaireResponseItem = { linkId };
  const answer = value['answer'];
  if (isRecord(answer)) {
    item.answer = toAnswers(answer, shape);
  }
  const children = toItems(childEntries(value), shape);
  return withChildren(item, children);
}

/**
 * Converts the `answer` object of an item into answers.
 *
 * A multi-select (`valueCoding` array) results in one answer per coding. Otherwise there is one answer
 * holding all `value*` entries, with the remaining entries as its child items.
 *
 * @param answer The `answer` object from the model.
 * @param shape Node of the item that owns the answer; its children describe the answer's child items.
 * @returns The answers of the item.
 */
function toAnswers(answer: Record<string, unknown>, shape: ItemShape | undefined): QuestionnaireResponseAnswer[] {
  const { valueCoding } = answer;
  if (Array.isArray(valueCoding)) {
    return valueCoding.map(coding => ({ valueCoding: withoutDesignations(coding) }));
  }

  const entries = Object.entries(answer);
  const valueEntries = entries.filter(([key]) => isValueKey(key));
  const childItemEntries = entries.filter(([key]) => !isValueKey(key));

  const result = Object.fromEntries(valueEntries) as QuestionnaireResponseAnswer;
  if (isRecord(result.valueCoding)) {
    result.valueCoding = withoutDesignations(result.valueCoding);
  }
  const items = toItems(childItemEntries, shape);
  if (items.length > 0) {
    result.item = items;
  }
  return [result];
}

/**
 * Returns the entries of a model object that are child items, i.e. all except the item's own `answer`.
 *
 * @param value Model object of an item or of one repetition.
 * @returns The child entries; empty for non-objects.
 */
function childEntries(value: unknown): ModelEntry[] {
  if (!isRecord(value)) {
    return [];
  }
  return Object.entries(value).filter(([key]) => !isAnswerKey(key));
}

/**
 * Adds child items to an item; omits the `item` property when there are none.
 *
 * @param item The item without children.
 * @param children Its child items.
 * @returns The item with children, or the unchanged item.
 */
function withChildren(item: QuestionnaireResponseItem, children: QuestionnaireResponseItem[]): QuestionnaireResponseItem {
  if (children.length === 0) {
    return item;
  }
  return { ...item, item: children };
}

/**
 * Removes the designations from a coding; they are display translations for the form and not part of
 * the notification.
 *
 * @param coding Coding from the model.
 * @returns A copy of the coding without designations.
 */
function withoutDesignations(coding: CodeDisplay): CodeDisplay {
  const { designations, ...rest } = coding;
  return rest;
}
